#ifndef MSORT_H
#define MSORT_H

#include <stddef.h>

/*
 * Параллельная сортировка слиянием массива arr длины n.
 * max_threads - максимальное число потоков, работающих одновременно
 *               (включая главный поток). При max_threads == 1 сортировка
 *               идёт последовательно, без создания потоков.
 * verbose     - если не 0, печатать TID создаваемых потоков.
 *
 * Возвращает 0 при успехе, -1 при ошибке (сообщение уже выведено в stderr).
 */
int parallel_merge_sort(int *arr, size_t n, int max_threads, int verbose);

/* Максимальное число потоков, которое реально работало одновременно
 * во время последней сортировки. */
int msort_peak_threads(void);

#endif
